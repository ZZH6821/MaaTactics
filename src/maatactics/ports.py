"""Ports shared by the application and interchangeable engine implementations."""

from collections.abc import Callable
from typing import Any, Protocol


class BattleBackend(Protocol):
    async def connect(self, profile: dict[str, Any]) -> dict[str, Any]: ...
    async def capture(self) -> bytes: ...
    async def observe(self, png: bytes) -> dict | None: ...
    async def set_stage(self, name: str) -> dict[str, Any]: ...
    async def execute(self, action: dict[str, Any]) -> dict[str, Any]: ...
    async def toggle_battle_pause(self) -> dict[str, Any]: ...
    async def toggle_battle_speed(self, target: int) -> dict[str, Any]: ...
    async def start_battle(self) -> dict[str, Any]: ...
    async def scan_operator_roster(self) -> dict[str, Any]: ...
    async def validate_copilot(self, document: dict) -> dict[str, Any]: ...
    async def execute_copilot(
        self,
        document: dict,
        formation: bool,
        on_event: Callable[[dict], None],
        hybrid: bool = False,
    ) -> dict[str, Any]: ...
    async def hybrid_state(self) -> dict[str, Any]: ...
    async def hybrid_command(self, command: dict) -> dict[str, Any]: ...
    async def stop(self) -> None: ...
    async def close(self) -> None: ...
